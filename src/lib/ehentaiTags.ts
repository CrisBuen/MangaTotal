function normalizarTextoTag(s: string): string {
  return s
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .trim();
}

/**
 * Busca etiquetas en el catálogo base que coincidan con el término y el namespace elegido.
 * Soporta listas separadas por coma ("tag1, tag2, parcial"): filtra según el
 * último término después de la última coma y excluye las ya agregadas.
 */
export function buscarEtiquetasEhentai(
  termino: string,
  nsFiltro: EhentaiNamespace = "todos"
): EhentaiTag[] {
  const partes = termino.split(",");
  let ultimo = normalizarTextoTag(partes[partes.length - 1] ?? "");
  let nsEfectivo: string = nsFiltro === "todos" ? "" : nsFiltro;

  const dp = ultimo.indexOf(":");
  if (dp > 0) {
    const pref = ultimo.slice(0, dp).trim();
    const mapeado = ABREVIATURAS_NS[pref] ?? pref;
    nsEfectivo = mapeado;
    ultimo = ultimo.slice(dp + 1).trim();
  }

  const previas = new Set(
    partes
      .slice(0, -1)
      .map((p) => p.trim().toLowerCase())
      .filter(Boolean)
  );

  let base = previas.size > 0
    ? EHENTAI_POPULAR_TAGS.filter((t) => !previas.has(t.tag.toLowerCase()))
    : EHENTAI_POPULAR_TAGS;

  if (nsEfectivo) {
    base = base.filter((t) => t.tag.toLowerCase().startsWith(`${nsEfectivo}:`));
  }

  if (!ultimo) return base;

  return base.filter((t) => {
    if (normalizarTextoTag(t.tag).includes(ultimo)) return true;
    if (normalizarTextoTag(t.label).includes(ultimo)) return true;
    if (t.aliases?.some((a) => normalizarTextoTag(a).includes(ultimo))) return true;
    return false;
  });
}
